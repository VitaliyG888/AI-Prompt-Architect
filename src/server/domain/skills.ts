/** Максимальная длина примера в промте: пример задаёт форму, а не объём. */
export const EXAMPLE_BODY_LIMIT = 1200;

export function truncateExample(body: string, limit = EXAMPLE_BODY_LIMIT): string {
  const trimmed = body.trim();
  if (trimmed.length <= limit) return trimmed;
  return `${trimmed.slice(0, limit).trimEnd()}…`;
}

/** id примеров, на которые ссылаются выбранные скиллы, в порядке скиллов. */
export function exampleIdsFor(skills: Skill[]): string[] {
  const seen = new Set<string>();
  const ids: string[] = [];
  for (const skill of skills) {
    for (const id of skill.exampleIds) {
      if (seen.has(id)) continue;
      seen.add(id);
      ids.push(id);
    }
  }
  return ids;
}
