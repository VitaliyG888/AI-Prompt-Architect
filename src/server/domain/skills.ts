export const SKILL_CATEGORY_ORDER: SkillCategory[] = ['sites', 'texts', 'marketing'];

/* ─────────────────────────── Подбор скиллов ─────────────────────────── */

export interface SkillSelectionInput {
  idea: string;
  sectionKey: SectionKey;
  archetype: ArchetypeId;
  /** Сколько скиллов вернуть. */
  limit?: number;
}

export interface SelectedSkill {
  skill: Skill;
  score: number;
  /** Почему скилл выбран — для прозрачности в интерфейсе. */
  reasons: string[];
}

const SECTION_WEIGHT = 4;
const ARCHETYPE_WEIGHT = 3;
const KEYWORD_WEIGHT = 2;

/**
 * Отбор скиллов для раздела. Детерминирован: при равном счёте порядок
 * задаётся id, поэтому один и тот же проект всегда даёт один и тот же набор.
 */
export function selectSkills(input: SkillSelectionInput): SelectedSkill[] {
  const haystack = input.idea.toLowerCase();
  const scored: SelectedSkill[] = [];

  for (const skill of SKILLS) {
    let score = 0;
    const reasons: string[] = [];

    if (skill.sections.includes(input.sectionKey)) {
      score += SECTION_WEIGHT;
      reasons.push(`раздел ${input.sectionKey}`);
    }
    if (skill.archetypes.length === 0 || skill.archetypes.includes(input.archetype)) {
      score += ARCHETYPE_WEIGHT;
      reasons.push(`архетип ${input.archetype}`);
    }
    const hits = skill.keywords.filter((keyword) => haystack.includes(keyword.toLowerCase()));
    if (hits.length > 0) {
      score += Math.min(hits.length, 3) * KEYWORD_WEIGHT;
      reasons.push(`тема: ${hits.slice(0, 3).join(', ')}`);
    }

    if (score > 0) scored.push({ skill, score, reasons });
  }

  scored.sort((a, b) => b.score - a.score || a.skill.id.localeCompare(b.skill.id));
  return scored.slice(0, input.limit ?? 3);
}

