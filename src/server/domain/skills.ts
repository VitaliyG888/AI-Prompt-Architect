/**
 * Реестр навыков (skills) для повышения качества разделов промта.
 *
 * Скилл — это не шаблон текста, а профессиональный чек-лист: что обязательно
 * должно быть в разделе, каких ошибок избегать и на какие примеры из
 * библиотеки промтов опираться. Скиллы подбираются детерминированно по
 * архетипу задачи, ключу раздела и ключевым словам идеи проекта.
 */
import type { ArchetypeId } from './archetypes.ts';
import type { SectionKey } from './types.ts';

export type SkillCategory = 'sites' | 'texts' | 'marketing';

export const SKILL_CATEGORY_LABELS: Record<SkillCategory, string> = {
  sites: 'Сайты и интерфейсы',
  texts: 'Тексты и копирайтинг',
  marketing: 'Маркетинг и стратегия',
};

export interface Skill {
  id: string;
  label: string;
  category: SkillCategory;
  /** Разделы промта, которые скилл усиливает. */
  sections: SectionKey[];
  /** Архетипы, для которых скилл уместен; пусто — для любого. */
  archetypes: ArchetypeId[];
  /** Слова темы проекта, включающие скилл. */
  keywords: string[];
  /** Что обязательно должно быть в разделе. */
  guidance: string[];
  /** Типичные ошибки, которых нужно избегать. */
  antiPatterns: string[];
  /** id примеров из prompt-library.json. */
  exampleIds: string[];
}

